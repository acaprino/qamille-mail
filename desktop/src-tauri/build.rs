//! Declares the app's commands to Tauri, so each window can call only the
//! commands its capability grants (`capabilities/*.json`). The list comes from
//! `generate_handler!` in `src/main.rs`, so a new command cannot be forgotten:
//! the main window gets every command except the meeting reminder chip's,
//! through the generated `permissions/main-window.toml`.
use std::fs;

const MAIN_WINDOW_SET: &str = "permissions/main-window.toml";

fn main() {
    println!("cargo:rerun-if-changed=src/main.rs");
    let source = fs::read_to_string("src/main.rs").expect("read src/main.rs");
    let commands = handler_commands(&source);
    let main_window: Vec<String> = commands
        .iter()
        .filter(|command| !command.starts_with("reminder_"))
        .map(|command| format!("  \"allow-{}\",", command.replace('_', "-")))
        .collect();
    write_if_changed(
        MAIN_WINDOW_SET,
        &format!(
            "# Generated by build.rs from generate_handler! in src/main.rs. Do not edit.\n\n\
             [[set]]\n\
             identifier = \"main-window-commands\"\n\
             description = \"Every app command except the meeting reminder chip's.\"\n\
             permissions = [\n{}\n]\n",
            main_window.join("\n")
        ),
    );
    let commands: Vec<&'static str> = commands
        .into_iter()
        .map(|command| &*Box::leak(command.into_boxed_str()))
        .collect();
    tauri_build::try_build(
        tauri_build::Attributes::new()
            .app_manifest(tauri_build::AppManifest::new().commands(Box::leak(commands.into_boxed_slice()))),
    )
    .expect("Tauri build failed");
}

/// The names in `generate_handler![...]`: the last path segment of each entry.
fn handler_commands(source: &str) -> Vec<String> {
    const OPEN: &str = "generate_handler![";
    let start = source.find(OPEN).expect("generate_handler! in src/main.rs") + OPEN.len();
    let end = start + source[start..].find(']').expect("end of generate_handler!");
    let list: String = source[start..end]
        .lines()
        .map(|line| line.split("//").next().unwrap_or_default())
        .collect::<Vec<_>>()
        .join(" ");
    let names: Vec<String> = list
        .split(',')
        .map(str::trim)
        .filter(|entry| !entry.is_empty())
        .map(|entry| entry.rsplit("::").next().unwrap_or(entry).to_string())
        .collect();
    assert!(
        names.len() > 3 && names.iter().all(|n| n.chars().all(|c| c.is_ascii_alphanumeric() || c == '_')),
        "unexpected command list in src/main.rs: {names:?}"
    );
    names
}

fn write_if_changed(path: &str, content: &str) {
    if fs::read_to_string(path).ok().as_deref() != Some(content) {
        fs::create_dir_all("permissions").expect("create permissions/");
        fs::write(path, content).expect("write the main window permission set");
    }
}
