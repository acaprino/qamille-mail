const GENERATED = '/* Generated by scripts/theme-css.mjs from src/theme/compatto.ts: do not edit. Run `npm run theme:css`. */';

const block = (selector, variables) =>
  `${selector} {\n${Object.entries(variables)
    .map(([name, value]) => `  ${name}: ${value};`)
    .join('\n')}\n}\n`;

/** The text of compatto.css for the Sigrid exports `sigrid` (its dist/index.js) and Qamille's parameters. */
export function compattoCss(sigrid, { COMPATTO, COMPATTO_TONE, QAMILLE_DENSITY }) {
  const density = sigrid.densityWith('compact', QAMILLE_DENSITY);
  const pick = (scheme) => ({ theme: COMPATTO, scheme, tone: COMPATTO_TONE });
  // Everything the engine owns comes with themeVariables: the colours, the shape (`--radius-*` from COMPATTO's `radii`) and
  // the elevations.
  const colours = (scheme) => sigrid.themeVariables(pick(scheme));
  return [
    GENERATED,
    block(':root', { ...sigrid.densityVariables(density), ...ALIASES }),
    block(":root:not([data-scheme]),\n:root[data-scheme='light']", colours('light')),
    block(":root[data-scheme='dark']", colours('dark')),
  ].join('\n');
}

export async function loadParameters() {
  return import(pathToFileURL(path.join(desktop, 'src', 'theme', 'compatto.ts')).href);
}

export async function loadSigrid() {
  return import(pathToFileURL(path.join(desktop, 'vendor', 'sigrid', 'dist', 'index.js')).href);
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  const css = compattoCss(await loadSigrid(), await loadParameters());
  writeFileSync(OUTPUT, css);
  console.log(`theme: ${path.relative(desktop, OUTPUT)} written (${css.split('\n').length} lines)`);
}
