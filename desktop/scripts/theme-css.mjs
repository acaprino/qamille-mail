  '--sidebar-text',
  '--sidebar-text-active',
  '--sidebar-muted',
  '--accent-on-sidebar',
  '--text',
  '--text-secondary',
  '--body-text',
  '--muted',
  '--nav-text',
  '--border',
  '--border-soft',
  '--border-strong',
  '--accent',
  '--accent-hover',
  '--accent-text',
  '--on-accent',
  '--accent-pro',
  '--ring',
  '--selection',
